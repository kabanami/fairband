"""Build the packaged inflation table from the IMF datamapper's JSON (spec 2026-11-10 7.3).

    uv run python scripts/build_inflation_table.py <json> <toml> (--indicators <json> | --vintage
        "October 2026") [--years 2027-2031] [--retrieved YYYY-MM-DD]

The first JSON is the response of ``URL``, the World Economic Outlook's ``PCPIPCH`` series
(inflation, average consumer prices, annual percent change), ``{"values": {"PCPIPCH": {"USA":
{"2027": 2.8, ...}}}}``, saved outside the repository; it is never committed. The vintage is read
from the ``source`` of ``PCPIPCH`` in the datamapper's ``indicators`` response, "World Economic
Outlook (October 2026)", given with ``--indicators``, else it is ``--vintage``. The years default
to the five after the retrieval's year, the retrieval date to the JSON's modification date.

Each currency of ``CURRENCY_ECONOMIES`` takes its issuing economy's projection for each year, a
percentage, as a fraction: the JSON's figure ÷ 100, read as a decimal so 1.9 is written 0.019;
a comment on the row gives their mean, the currency's π. A currency whose economy lacks a year is
left out, with a line on stderr naming it. The file written is loaded back through
``load_inflation_table`` before the script reports, so a table the engine would refuse fails here.
"""

import argparse
import json
import re
import sys
import textwrap
from datetime import date
from decimal import Decimal
from pathlib import Path

from fairband.policy.inflation import load_inflation_table

INDICATOR = "PCPIPCH"
URL = f"https://www.imf.org/external/datamapper/api/v1/{INDICATOR}"
YEARS_AFTER = 5

# Each currency's issuing economy, by the WEO's code: ISO 3166-1 alpha-3, and EURO for the euro
# area. The 23 reporting currencies of the foreign filers on file (spec section 5) and the other
# currencies FMP lists pairs for among the economies the WEO projects.
CURRENCY_ECONOMIES = {
    "USD": "USA",
    "EUR": "EURO",
    "GBP": "GBR",
    "JPY": "JPN",
    "CAD": "CAN",
    "CNY": "CHN",
    "HKD": "HKG",
    "TWD": "TWN",
    "KRW": "KOR",
    "INR": "IND",
    "SGD": "SGP",
    "AUD": "AUS",
    "NZD": "NZL",
    "CHF": "CHE",
    "SEK": "SWE",
    "NOK": "NOR",
    "DKK": "DNK",
    "PLN": "POL",
    "CZK": "CZE",
    "HUF": "HUN",
    "ILS": "ISR",
    "AED": "ARE",
    "SAR": "SAU",
    "QAR": "QAT",
    "KWD": "KWT",
    "ZAR": "ZAF",
    "BRL": "BRA",
    "MXN": "MEX",
    "ARS": "ARG",
    "CLP": "CHL",
    "COP": "COL",
    "PEN": "PER",
    "TRY": "TUR",
    "IDR": "IDN",
    "PHP": "PHL",
    "THB": "THA",
    "MYR": "MYS",
    "VND": "VNM",
    "KZT": "KAZ",
    "EGP": "EGY",
    "NGN": "NGA",
    "RUB": "RUS",
}

_VINTAGE = re.compile(r"World Economic Outlook \(([A-Z][a-z]+ \d{4})\)")
_HEADER = (
    "Expected inflation by currency: the IMF World Economic Outlook's projections of consumer "
    "price inflation for the five years after the retrieval's year, as fractions (spec "
    "2026-11-10 7.3)."
)
_GENERATED = (
    "# Generated by scripts/build_inflation_table.py from the datamapper's JSON; edit the script."
)


def read_series(path: Path) -> dict[str, dict[str, Decimal]]:
    """Each economy's figures by year, as decimals; a figure that is not a number is left out."""
    raw = json.loads(path.read_text(encoding="utf-8"), parse_float=Decimal, parse_int=Decimal)
    try:
        series = raw["values"][INDICATOR]
    except (KeyError, TypeError) as e:
        raise SystemExit(f"{path}: no values.{INDICATOR}") from e
    return {
        economy: {year: x for year, x in figures.items() if isinstance(x, Decimal)}
        for economy, figures in series.items()
    }


def read_vintage(path: Path) -> str:
    """The month and year in the ``source`` of ``PCPIPCH`` in the ``indicators`` response."""
    raw = json.loads(path.read_text(encoding="utf-8"))
    try:
        source = raw["indicators"][INDICATOR]["source"]
    except (KeyError, TypeError) as e:
        raise SystemExit(f"{path}: no indicators.{INDICATOR}.source") from e
    found = _VINTAGE.fullmatch(str(source))
    if found is None:
        raise SystemExit(f"{path}: the source {source!r} names no World Economic Outlook vintage")
    return found.group(1)


def projections(
    series: dict[str, dict[str, Decimal]], years: range
) -> tuple[dict[str, tuple[str, list[Decimal]]], list[str]]:
    """Each currency's economy and its rates as fractions, and a line for each currency left out
    for want of a year."""
    rows: dict[str, tuple[str, list[Decimal]]] = {}
    left_out: list[str] = []
    for code, economy in sorted(CURRENCY_ECONOMIES.items()):
        figures = series.get(economy)
        if figures is None:
            left_out.append(f"{code}: {economy} is not in the series")
            continue
        missing = [str(y) for y in years if str(y) not in figures]
        if missing:
            left_out.append(f"{code}: {economy} has no projection for {', '.join(missing)}")
            continue
        rows[code] = (economy, [figures[str(y)] / 100 for y in years])
    return rows, left_out


def render(
    rows: dict[str, tuple[str, list[Decimal]]], vintage: str, retrieved: str, years: range
) -> str:
    """The table: the header, ``[meta]``, one ``[[currencies]]`` row a currency with its mean."""
    source = (
        f"IMF World Economic Outlook, {vintage}: inflation, average consumer prices "
        f"({INDICATOR}), annual percent change"
    )
    lines = [
        *(f"# {line}" for line in textwrap.wrap(_HEADER, 98, break_on_hyphens=False)),
        _GENERATED,
        "",
        "[meta]",
        f"source = {_string(source)}",
        f"url = {_string(URL)}",
        f"vintage = {_string(vintage)}",
        f"retrieved = {_string(retrieved)}",
        f"years = [{', '.join(str(y) for y in years)}]",
    ]
    for code, (economy, rates) in rows.items():
        mean = sum(rates, Decimal(0)) / len(rates)
        lines += [
            "",
            "[[currencies]]",
            f"code = {_string(code)}",
            f"economy = {_string(economy)}",
            f"rates = [{', '.join(repr(float(r)) for r in rates)}]  # mean {float(mean)!r}",
        ]
    return "\n".join(lines) + "\n"


def _string(value: str) -> str:
    """A TOML basic string: JSON's escapes are TOML's."""
    return json.dumps(value, ensure_ascii=False)


def _years(text: str) -> range:
    first, _, last = text.partition("-")
    try:
        years = range(int(first), int(last) + 1)
    except ValueError as e:
        raise argparse.ArgumentTypeError(f"{text!r} is not a span of years, 2027-2031") from e
    if not years:
        raise argparse.ArgumentTypeError(f"{text!r} is not a span of years, 2027-2031")
    return years


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("json", type=Path, help=f"the datamapper's {INDICATOR} response")
    parser.add_argument("toml", type=Path, help="the inflation table to write")
    vintage = parser.add_mutually_exclusive_group(required=True)
    vintage.add_argument(
        "--indicators", type=Path, help="the datamapper's indicators response, for the vintage"
    )
    vintage.add_argument("--vintage", help='the WEO vintage, "October 2026"')
    parser.add_argument(
        "--years",
        type=_years,
        help="the projection years, 2027-2031 (default: the five after the retrieval's year)",
    )
    parser.add_argument(
        "--retrieved",
        type=date.fromisoformat,
        help="the date the JSON was fetched (default: its modification date)",
    )
    args = parser.parse_args(argv)
    retrieved = args.retrieved or date.fromtimestamp(args.json.stat().st_mtime)
    years = args.years or range(retrieved.year + 1, retrieved.year + 1 + YEARS_AFTER)
    vintage_name = read_vintage(args.indicators) if args.indicators else args.vintage
    rows, left_out = projections(read_series(args.json), years)
    for line in left_out:
        print(f"left out: {line}", file=sys.stderr)
    args.toml.write_text(render(rows, vintage_name, retrieved.isoformat(), years), encoding="utf-8")
    table = load_inflation_table(args.toml)
    print(
        f"{args.toml}: {len(rows)} currencies of {len(CURRENCY_ECONOMIES)}, the World Economic "
        f"Outlook of {table.vintage}, {years[0]} to {years[-1]}"
    )


if __name__ == "__main__":
    main()
