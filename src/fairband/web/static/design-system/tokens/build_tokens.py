#!/usr/bin/env python3
"""Compile tokens.json into tokens.css.

tokens.json is the source of truth; tokens.css is generated and should never be
hand-edited. Re-run this after pulling a new tokens.json from the design system:

    python3 tokens/build_tokens.py

Output layout, which matches what the design system's own page compiles:

    :root, [data-theme="dark"]   colour + shadow tokens for the first theme
    [data-theme="light"]         the same names, that theme's values
    :root                        spacing, radius, size, --font-<family>
    .<style>                     one class per type style

The first theme in tokens.json is the default. A token with no value for a
later theme inherits the first theme's value, so only real differences need to
be declared.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "tokens.json"
OUT = HERE / "tokens.css"

ALIAS = re.compile(r"^\{(.+)\}$")
# Families whose tokens are plain name/value pairs rendered once, not per theme.
FLAT_FAMILIES = ("spacing", "radius", "size")
# Families that carry per-theme values alongside colour.
THEMED_FAMILIES = ("shadow",)


def resolve(value, theme: str, first: str) -> str:
    """A value may be a plain string or a {theme: value} map; `{other}` is an alias."""
    if isinstance(value, dict):
        raw = value.get(theme, value.get(first))
    else:
        raw = value
    raw = str(raw)
    alias = ALIAS.match(raw)
    return f"var(--{alias.group(1)})" if alias else raw


def declarations(tokens: dict, theme: str, first: str) -> list[str]:
    out = []
    for family in ("color",) + THEMED_FAMILIES:
        block = tokens.get(family)
        if not block:
            continue
        for token in block["tokens"]:
            out.append(f"  --{token['name']}: {resolve(token['value'], theme, first)};")
    return out


def build(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    first = themes[0]
    lines: list[str] = [
        f"/* {tokens.get('name', 'Design system')} tokens, version "
        f"{tokens.get('version', 1)} — generated by build_tokens.py. Do not edit. */",
        "",
        f':root, [data-theme="{first}"] {{',
        *declarations(tokens, first, first),
        "}",
        "",
    ]

    for theme in themes[1:]:
        lines += [
            f'[data-theme="{theme}"] {{',
            *declarations(tokens, theme, first),
            "}",
            "",
        ]

    # Follow the operating system until the reader picks a theme explicitly.
    if len(themes) > 1:
        lines += [
            f"@media (prefers-color-scheme: {themes[1]}) {{",
            "  :root:not([data-theme]) {",
            *[f"  {d}" for d in declarations(tokens, themes[1], first)],
            "  }",
            "}",
            "",
        ]

    scalars: list[str] = []
    for family in FLAT_FAMILIES:
        block = tokens.get(family)
        if not block:
            continue
        for token in block["tokens"]:
            scalars.append(f"  --{token['name']}: {token['value']};")
    for key, stack in tokens["type"]["families"].items():
        scalars.append(f"  --font-{key}: {stack};")
    lines += [":root {", *scalars, "}", ""]

    for group in tokens["type"]["groups"]:
        for style in group["styles"]:
            family = style.get("family", group["family"])
            parts = [
                f"font-family: var(--font-{family})",
                f"font-size: {style['fontSize']}",
                f"line-height: {style['lineHeight']}",
                f"font-weight: {style['fontWeight']}",
            ]
            if style.get("letterSpacing"):
                parts.append(f"letter-spacing: {style['letterSpacing']}")
            if style.get("fontStyle"):
                parts.append(f"font-style: {style['fontStyle']}")
            lines.append(f".{style['name']} {{ " + "; ".join(parts) + "; }")

    return "\n".join(lines) + "\n"


def main() -> int:
    if not SRC.exists():
        print(f"missing {SRC}", file=sys.stderr)
        return 1
    css = build(json.loads(SRC.read_text(encoding="utf-8")))
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT} ({len(css)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
